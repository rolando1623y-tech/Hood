package com.panahoops.next

fun main() {
    val start = FitCounter.accept(null, 20, "2026-10-18", 15400, 1000)
    check(start.steps == 0L)
    val next = FitCounter.accept(start, 20, "2026-10-18", 15445, 2000)
    check(next.steps == 45L)
    check(FitCounter.accept(next, 20, "2026-10-18", 15445, 3000).steps == 45L)
    check(FitCounter.accept(next, 20, "2026-10-18", 15430, 3000).steps == 45L)
    check(FitCounter.accept(next, 21, "2026-10-18", 22, 3000).steps == 45L)
    check(FitCounter.accept(next, 20, "2026-10-19", 15500, 3000).steps == 0L)
    check(FitCounter.accept(FitCounter.reset(next), 20, "2026-10-18", 15465, 4000).steps == 20L)
    check(FitCounter.accept(next, 20, "2026-10-18", 15446, 1999) == next)
    check(FitCounter.accept(next, 20, "2026-10-18", 500000, 5000).steps == 45L)
    check(FpsPolicy.best(listOf(15 to 30, 30 to 30, 30 to 60), 60) == 30 to 60)
    check(FpsPolicy.best(listOf(30 to 30, 60 to 60, 30 to 120), 120) == 30 to 120)
    check(FpsPolicy.best(listOf(15 to 30, 30 to 30), 120) == 30 to 30)
    check(FpsPolicy.best(listOf(30 to 60), 30) == null)
    check(ResetPolicy.matches("DAY", 100, 200, "", "session", 100, "x", "", "routine"))
    check(!ResetPolicy.matches("DAY", 100, 200, "", "session", 200, "x", "", "routine"))
    check(ResetPolicy.matches("PLAYER", 0, 999, "Uno", "match", 100, "m1", "uno", ""))
    check(!ResetPolicy.matches("PLAYER", 0, 999, "Uno", "match", 100, "m1", "dos", ""))
    check(ResetPolicy.matches("SHOTS", 0, 999, "", "shot", 100, "x", "", ""))
    check(!ResetPolicy.matches("SHOTS", 0, 999, "", "session", 100, "x", "", ""))
    check(ResetPolicy.matches("MODE", 0, 999, "camera", "session", 100, "x", "", "camera"))
    check(ResetPolicy.matches("FIT", 0, 999, "", "fit", 100, "x", "", ""))
    check(!ResetPolicy.matches("FIT", 0, 999, "", "match", 100, "x", "", ""))
    check(FitDistance.meters(0,70) == 0.0)
    check(FitDistance.meters(1500,70) == 1050.0)
    check(FitDistance.meters(1500,100) == 1500.0)
    check(runCatching { FitDistance.meters(-1,70) }.isFailure)
    check(runCatching { FitDistance.meters(100,0) }.isFailure)
    check(runCatching { FitDistance.meters(100,151) }.isFailure)
    println("OK: 28 comprobaciones sintéticas de sensor, FPS, borrado y distancia")
}
